namespace TurboLuxury.WaterSaver;

/// <summary>Ways of washing a car.</summary>
public enum WashMethod
{
    /// <summary>Open garden hose left running.</summary>
    Hose,
    /// <summary>Electric pressure washer.</summary>
    PressureWasher,
    /// <summary>Two buckets (wash and rinse) with a hose rinse kept short.</summary>
    Bucket,
    /// <summary>Rinseless wash: one bucket of solution, no hose rinse.</summary>
    Rinseless,
    /// <summary>Waterless spray and microfibre towels.</summary>
    Waterless,
}
